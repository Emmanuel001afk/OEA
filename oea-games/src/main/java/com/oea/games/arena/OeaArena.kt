        if (z.enabled) {
            val t = max(0f, z.timer).toInt()
            val cx = w / 2f; val cy = y + 2f * d
            tmp.set(z.cx, 8f, z.cz)
            camera.worldToScreen(tmp, w, h, tmp2)
