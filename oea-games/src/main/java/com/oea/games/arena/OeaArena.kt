    // ---------------------------------------------------------------- per frame

    override fun onUpdate(dt: Float) {
        renderDt = dt
        val g = ctx.graphics
        val w = g.width.toFloat(); val h = g.height.toFloat(); val d = g.density
        if (w > 0f && h > 0f) applyOrientationControls(w < h)
        val me = local
        val alive = me?.alive == true && !matchOver
        val sl = g.safeInsets[0].toFloat(); val sr = g.safeInsets[2].toFloat()
        // Round modes: phase 1 = round over (result, then shop), phase 2 = shop/pick prep.
        if (sim.roundMode && !studio.open) {
            if (!roundDialogOpen && !shopOpen) {
                if (sim.roundPhase == 1) {
                    roundDialogOpen = true
                    openRoundOverDialog()
                } else if (sim.roundPhase == 2) {
                    shopOpen = true
                    openShopOrPick()
                }
            }
        }
        // Controls: buttons first (they claim fingers), then the stick and the look area.
        val near = me?.let { sim.nearestLoot(it, LootKind.WEAPON) ?: sim.nearestLoot(it, LootKind.GRENADE) }
        pickupBtn.visible = alive && near != null && !(me?.skydiving ?: true)
        pickupBtn.label = near?.let { Weapon.entries[it.value].glyph } ?: "PICK"
        healBtn.visible = alive && (me?.medkits ?: 0) > 0
        healBtn.progress = me?.healProgress?.takeIf { it > 0f } ?: -1f
        // In the Character Studio the game controls stand down completely so
        // every tap lands on the studio overlay instead of the fire button.
        val controlsPaused = studio.open
        for ((b, _) in controlButtons) {
            b.enabled = alive || controlsOpen // the layout screen stays draggable while dead
            b.paused = controlsPaused && !controlsOpen
            b.editing = controlsOpen
            if (controlsOpen) b.progress = -1f
            b.update(ctx.input, w, h, d, sl, sr)
        }
        // Controls screen: screen buttons update first (justPressed), then the
        // drag handling reads the game buttons' per-frame drag delta (px).
        for (b in listOf(ctrlDone, ctrlReset, ctrlAds, ctrlSmaller, ctrlBigger)) {
            b.paused = !controlsOpen
            b.visible = controlsOpen
            b.update(ctx.input, w, h, d, sl, sr)
        }
        if (controlsOpen) {
            for (b in listOf(ctrlSmaller, ctrlBigger)) b.editing = false
            for ((b, key) in controlButtons) {
                if (b.justPressed) selectedKey = key
                if (b.dragDx != 0f || b.dragDy != 0f) {
                    b.anchorX = (b.anchorX + b.dragDx / w).coerceIn(0.04f, 0.96f)
                    b.anchorY = (b.anchorY + b.dragDy / h).coerceIn(0.04f, 0.96f)
                    saveButtonLayout()
                }
            }
            // Size: the two keys resize whichever control was last tapped, and a
            // second tap on the same control steps it too, so one thumb can do it.
            val sizeStep = if (ctrlSmaller.pressed || ctrlSmaller.justPressed) -1.5f else if (ctrlBigger.pressed || ctrlBigger.justPressed) 1.5f else 0f
            if (sizeStep != 0f) {
                selectedKey?.let { key ->
                    controlButtons.firstOrNull { it.second == key }?.let { (button, _) ->
                        button.radiusDp = (button.radiusDp + sizeStep).coerceIn(16f, 72f)
                        saveButtonLayout()
                        ctx.haptics.tick()
                    }
                }
            }
            if (ctrlDone.justPressed) {
                controlsOpen = false
                selectedKey = null
                saveButtonLayout()
                ctx.ui.toast("Layout saved")
            }
            if (ctrlReset.justPressed) {
                resetButtonLayout()
                selectedKey = null
            }
            if (ctrlAds.justPressed) {
                adsHoldMode = !adsHoldMode
                ctrlAds.label = if (adsHoldMode) "ADS · HOLD" else "ADS · TAP"
                saveButtonLayout()
            }
        }
        // Throwable pack: the buttons carry their own counts.
        stunBtn.label = if ((me?.stuns ?: 0) > 0) "STUN ${me!!.stuns}" else "—"
        fragBtn.label = if ((me?.grenades ?: 0) > 0) "FRAG ${me!!.grenades}" else "—"
        smokeBtn.label = if ((me?.smokes ?: 0) > 0) "SMK ${me!!.smokes}" else "—"
        joystick.paused = controlsPaused
        look.paused = controlsPaused
        joystick.update(ctx.input, w, h, d, dt)
        look.update(ctx.input, w, h, dt)
        val zoom = if (adsOn) (me?.weapon?.zoom ?: 1f) else 1f
        // Sensitivity: base × ADS multiplier ÷ zoom, then the turn-rate cap —
        // the cap is what keeps a glitched pointer or a wild stick from ever
        // spinning the camera faster than a real hand can turn.
        var sens = 0.0038f * ctx.settings.lookSensitivity / d
        if (adsOn) sens *= adsSens
        sens /= zoom
        val maxDelta = 0.28f * min(w, h) // no real drag moves this far in one frame
        val dx = (look.deltaX + fire.dragDx + fire2.dragDx).coerceIn(-maxDelta, maxDelta)
        val dy = (look.deltaY + fire.dragDy + fire2.dragDy).coerceIn(-maxDelta, maxDelta)
        val inv = if (invertY) -1f else 1f
        val yawStep = dx * sens * 1.15f
        val pitchStep = dy * sens * inv
        if (turnLimit > 0f) {
            val maxYaw = turnLimit * dt
            val maxPitch = turnLimit * dt
            lookYaw = wrapYaw(lookYaw - yawStep.coerceIn(-maxYaw, maxYaw))
            lookPitch = MathX.clamp(lookPitch - pitchStep.coerceIn(-maxPitch, maxPitch), -1.2f, 1.1f)
        } else {
            lookYaw = wrapYaw(lookYaw - yawStep)
            lookPitch = MathX.clamp(lookPitch - pitchStep, -1.2f, 1.1f)
        }
        // Gamepad / keyboard: the same turn limit, so sticks and thumbs agree.
        val gp = ctx.input.gamepad
        if (gp.connected) {
            val gpYaw = gp.rightX * dt * 2.6f / zoom
            val gpPitch = gp.rightY * dt * 1.8f / zoom * inv
            if (turnLimit > 0f) {
                val maxYaw = turnLimit * dt
                lookYaw = wrapYaw(lookYaw - gpYaw.coerceIn(-maxYaw, maxYaw))
                lookPitch = MathX.clamp(lookPitch - gpPitch.coerceIn(-maxYaw, maxYaw), -1.2f, 1.1f)
            } else {
                lookYaw = wrapYaw(lookYaw - gpYaw)
                lookPitch = MathX.clamp(lookPitch - gpPitch, -1.2f, 1.1f)
            }
        }
        // All gameplay button state stands down while the controls screen is open —
        // taps there move buttons, not the soldier.
        if (!controlsOpen) {
            if (adsHoldMode) {
                if (adsBtn.justPressed || adsBtn.justReleased) adsOn = adsBtn.pressed
                if (ctx.input.keys.justPressed(KeyEvent.KEYCODE_SHIFT_LEFT) || gp.justPressed(KeyEvent.KEYCODE_BUTTON_L2)) adsOn = !adsOn
            } else if (adsBtn.justPressed || ctx.input.keys.justPressed(KeyEvent.KEYCODE_SHIFT_LEFT) || gp.justPressed(KeyEvent.KEYCODE_BUTTON_L2)) {
                adsOn = !adsOn
            }
            if (ctx.input.keys.justPressed(KeyEvent.KEYCODE_C) || gp.justPressed(KeyEvent.KEYCODE_BUTTON_B)) {
                if (proneOn) { proneOn = false; crouchOn = true } else crouchOn = !crouchOn
            }
            if (jumpBtn.justPressed || ctx.input.keys.justPressed(KeyEvent.KEYCODE_SPACE) || gp.justPressed(KeyEvent.KEYCODE_BUTTON_A)) { jumpLatch = true; crouchOn = false; proneOn = false }
            if (reloadBtn.justPressed || ctx.input.keys.justPressed(KeyEvent.KEYCODE_R) || gp.justPressed(KeyEvent.KEYCODE_BUTTON_X)) reloadLatch = true
            if (ctx.input.keys.justPressed(KeyEvent.KEYCODE_G) && me?.alive == true && !me.skydiving) grenadeLatch = 0
            if (ctx.input.keys.justPressed(KeyEvent.KEYCODE_H) && me?.alive == true && !me.skydiving) grenadeLatch = 1
            if (ctx.input.keys.justPressed(KeyEvent.KEYCODE_I) && me?.alive == true && !me.skydiving) grenadeLatch = 2
            if (pickupBtn.justPressed && near != null) pickupLatch = near.id
            if (mountBtn.justPressed || ctx.input.keys.justPressed(KeyEvent.KEYCODE_E) || gp.justPressed(KeyEvent.KEYCODE_BUTTON_Y)) mountLatch = true
        // Frag: a tap throws on the normal fuse; holding cooks the fuse and the
        // throw fires on release with whatever is left — the pull-pin mechanic.
        if (fragBtn.pressed) {
            if (!wasFragHeld) cookTimer = 0f
            cookTimer += dt
            if (cookTimer > 0.3f) fragBtn.highlight = true
        } else {
            fragBtn.highlight = false
            if (wasFragHeld && me?.alive == true && !me.skydiving) {
                grenadeLatch = 0
                cookAmount = if (cookTimer >= 0.3f) cookTimer else 0f
            }
            cookTimer = 0f
        }
        wasFragHeld = fragBtn.pressed
        if (smokeBtn.justPressed && me?.alive == true && !me.skydiving) grenadeLatch = 1
        if (stunBtn.justPressed && me?.alive == true && !me.skydiving) grenadeLatch = 2
        // Prone: hold crouch for half a second to lie flat; tap to crouch back.
        if (crouchBtn.justPressed) {
            if (proneOn) { proneOn = false; crouchOn = true } else crouchOn = !crouchOn
            crouchHold = 0f
        }
        if (crouchBtn.pressed) {
            crouchHold += dt
            if (crouchHold >= 0.5f && !proneOn) { proneOn = true; crouchOn = false }
        } else crouchHold = 0f
        if (ctx.input.keys.justPressed(KeyEvent.KEYCODE_Z) && me?.alive == true) {
            proneOn = !proneOn
            if (proneOn) crouchOn = false
        }
        } // !controlsOpen
        if (gp.justPressed(KeyEvent.KEYCODE_BUTTON_Y)) { slotLatch = 1 - (me?.active ?: 0); if (slotLatch >= 0) switchDip = 0.25f }
        if (me?.weapon == Weapon.PAN) adsOn = false
        if (me != null && me.alive && me.recoil != 0f) {
            // Recoil (host simulation or client snapshot) kicks the sight up;
            // the kick decays smoothly so the crosshair recovers like a real gun.
            recoilPitch += me.recoil
            // Alternating side drift: a real weapon walks the sight picture
            // slightly left/right as it climbs, and settles back the same way.
            recoilYaw += me.recoil * (if (recoilPitch > 0f) 0.28f else -0.28f)
            me.recoil = 0f
        }
        if (recoilPitch != 0f) {
            recoilPitch *= MathX.damp(1f, 0f, 8f, dt)
            if (kotlin.math.abs(recoilPitch) < 0.002f) recoilPitch = 0f
        }
        if (recoilYaw != 0f) {
            // Recovers slower than the climb: a settle, not a snap-back.
            recoilYaw *= MathX.damp(1f, 0f, 4.5f, dt)
            if (kotlin.math.abs(recoilYaw) < 0.002f) recoilYaw = 0f
        }
        if (switchDip != 0f) {
            switchDip *= MathX.damp(1f, 0f, 10f, dt)
            if (switchDip < 0.002f) switchDip = 0f
        }
        if (shake > 0f) shake *= MathX.damp(1f, 0f, 5f, dt)
        // Visual effects.
        sparks.update(dt); puffs.update(dt)
        // Physics VFX: the air everyone breathes (weather, smoke, wind) and the
        // world's effect on the characters — wet cloth, dust on armour, hair
        // in the wind.
        vfx.sparkDensity = ctx.graphics.quality.particleDensity
        val fxList = ArrayList<CharFx>(actors.size + 1)
        fxList.add(myFx)
        for (a in actors.values) fxList.add(a.fx)
        if (isAuthority) for (p in sim.players.values) if (p.id != localId) fxList.add(actorFx.getOrPut(p.id) { CharFx() })
        vfx.update(dt, fxList)
        if (rules == "haunted") {
            fogTimer -= dt
            if (fogTimer <= 0f) {
                fogTimer = 2.5f
                val lx = local?.pos?.x ?: 0f; val lz = local?.pos?.z ?: 0f
                vfx.fogBank(lx, map.heightAt(lx, lz), lz, radius = 16f, density = 0.55f)
            }
        }
        val it = tracers.iterator()
        while (it.hasNext()) { val t = it.next(); t[6] += dt; if (t[6] > 0.09f) it.remove() }
        val dn = damageNumbers.iterator()
        while (dn.hasNext()) { val n = dn.next(); n[4] += dt; n[1] += dt * 0.8f; if (n[4] > 0.9f) dn.remove() }
        if (hitMarker > 0f) hitMarker -= dt else hitMarkerKill = false
        if (damageFrom > 0f) damageFrom -= dt
        if (respawnCountdown > 0f) {
            respawnCountdown -= dt
            if (me?.alive == true) respawnCountdown = -1f
        }
        // Ground contact: a hard landing throws dust and kicks the view, a
        // slide drags a trail. Both read the sim's surface, so the effect
        // always matches what the boots are actually on.
        val lp = local
        if (lp != null && lp.alive) {
            val landing = lp.landImpact
            if (landing > 0.35f && landing > lastLandImpact + 0.02f) {
                val gy = map.heightAt(lp.pos.x, lp.pos.z) + 0.04f
                val puff = if (lp.surface == ArenaMap.Surface.WATER) 0.9f else 0.55f * landing
                vfx.dustPuff(lp.pos.x, gy, lp.pos.z, puff)
                if (lp.surface == ArenaMap.Surface.WATER) vfx.dustPuff(lp.pos.x, gy + 0.1f, lp.pos.z, 0.7f)
                ctx.audio.play(sStep, 0.45f * landing, pitch = 0.7f)
                shake = max(shake, landing * 0.35f)
            }
            lastLandImpact = landing
            if (lp.sliding) {
                slideFxTimer -= dt
                if (slideFxTimer <= 0f) {
                    slideFxTimer = 0.09f
                    vfx.dustPuff(lp.pos.x, map.heightAt(lp.pos.x, lp.pos.z) + 0.05f, lp.pos.z, 0.3f)
                }
            } else slideFxTimer = 0f
        }
        // Airborne debris rides the wind: autumn leaves, spring blossom, snow
        // spindrift and badlands sand. One emitter, coloured by the season, so
        // the air is visibly the same system that pushes the soldiers.
        if (lp != null) ambientTimer -= dt
        if (ambientTimer <= 0f && lp != null) {
            ambientTimer = 0.08f
            map.windAt(ctx.time.elapsed.toFloat(), windTmp)
            val (col, life, size) = when {
                season == "autumn" -> Triple(0xF7B2670Au.toInt(), 3.4f, 0.11f)
                season == "spring" -> Triple(0xE8F2C0D8u.toInt(), 3.0f, 0.09f)
                season == "winter" || map.snowCover > 0.4f -> Triple(0xDDEDF2F7u.toInt(), 2.4f, 0.07f)
                map.levelStyle == "badlands" -> Triple(0x66C9B9A0.toInt(), 1.9f, 0.14f)
                else -> Triple(0x55D8E0C8u.toInt(), 2.2f, 0.08f)
            }
            val px = lp.pos.x + (kotlin.random.Random.nextFloat() - 0.5f) * 26f
            val pz = lp.pos.z + (kotlin.random.Random.nextFloat() - 0.5f) * 26f
            val py = map.heightAt(px, pz) + 1.2f + kotlin.random.Random.nextFloat() * 5f
            puffs.emit(px, py, pz, windTmp[0] * 1.4f, -0.6f - kotlin.random.Random.nextFloat() * 0.7f, windTmp[1] * 1.4f,
                life, size, size * 0.6f, col, col and 0x00FFFFFF,
                gravity = 0.25f, drag = 1.1f, spin = 2.4f)
        }
        // Seasons, sky, sun arc and fog are one continuous state for every mode.
        worldEnv.update(dt)
        // Remote actors.
        val now = net?.now() ?: 0L
        for (a in actors.values) {
            if (a.id == localId) continue
            if (a.buffer.sample(now, a.view)) {
                val moved = MathX.length(a.view[0] - a.lastX, a.view[2] - a.lastZ)
                a.speed01 = MathX.clamp01(moved * 28f)
                a.walk += moved * 2.2f
                // Which way they are drifting relative to the way they face.
                a.lateral = (if (moved > 1e-4f) ((a.view[0] - a.lastX) * -cos(a.view[3]) + (a.view[2] - a.lastZ) * sin(a.view[3])) / max(1e-4f, moved) else 0f).coerceIn(-1f, 1f)
                a.lastX = a.view[0]; a.lastZ = a.view[2]
            }
        }
        updateCamera(dt)
        publishIsland()
    }

    private fun updateCamera(dt: Float) {
        if (studio.open) {
            // Character Studio: a slow turntable around the live model.
            val me = local ?: return
            val orbit = ctx.time.elapsed.toFloat() * 0.35f
            val cx = me.pos.x + sin(orbit) * 2.4f
            val cy = me.pos.y + 1.55f
            val cz = me.pos.z + cos(orbit) * 2.4f
            camPos.set(cx, cy, cz)
            camera.position.set(camPos)
            camera.target.set(me.pos.x, me.pos.y + 1.05f, me.pos.z)
            camera.fovY = 52f * MathX.DEG_TO_RAD
            camera.near = 0.1f
            camera.far = 420f
            return
        }
        val alpha = ctx.time.alpha
        val target = viewTarget()
        val (px, py, pz) = target
        val me = local
        // Landing and sliding reshape the camera instead of teleporting it:
        // a hard landing drops the eye and rolls the horizon slightly, and a
        // slide leans the view downhill. Both decay with the body state.
        val impact = me?.landImpact ?: 0f
        val dip = impact * 0.36f
        val lean = if (me?.sliding == true) 0.06f else 0f
        val yaw: Float; val pitch: Float
        if (me != null && me.alive) { yaw = lookYaw + recoilYaw; pitch = lookPitch }
        else { yaw = lookYaw; pitch = MathX.clamp(lookPitch, -0.6f, 0.6f) }
        // Recoil rise, the reload dip and the switch jolt reshape the sight
        // picture without touching the input — the crosshair stays glued to shots.
        val kick = recoilPitch + switchDip + if ((me?.reloadLeft ?: 0f) > 0f) 0.1f else 0f
        val sightPitch = pitch + kick
        val skydive = me?.skydiving == true && me.alive
        val ads = adsOn && me?.alive == true && !skydive
        val zoom = if (ads) me?.weapon?.zoom ?: 1f else 1f
        val eyeY = py + when {
            me?.prone == true -> 0.8f
            me?.crouching == true -> 1.15f
            else -> 1.7f
        } - dip
        val fx = sin(yaw); val fz = cos(yaw)
        val rx = -fz; val rz = fx
        // ADS blends the whole camera: field of view, offset and stance.
        val backHip = 3.0f
        val backAds = if (zoom > 2f) 0.05f else 1.6f
        val back = if (skydive) 7f else MathX.lerp(backHip, backAds, adsBlend)
        val sideAds = if (zoom > 2f) 0f else 0.62f
        val side = MathX.lerp(0.62f, sideAds, adsBlend)
        val cp = cos(sightPitch)
        val lx = fx * cp; val ly = sin(sightPitch); val lz = fz * cp
        // Weapon bob: still hands when standing, a live body when moving —
        // but the sights settle when the weapon is aimed.
        val mov = joystick.magnitude
        val t = ctx.time.elapsed.toFloat()
        val bobScale = (1f - adsBlend * 0.8f) * (1f - (me?.spread ?: 0f) * 0.5f)
        val bobY = sin(t * 9f) * 0.05f * mov * bobScale
        val bobX = cos(t * 4.5f) * 0.035f * mov * bobScale
        var cx = px + rx * side - lx * back + bobX
        var cy = eyeY + 0.3f - ly * back + bobY
        var cz = pz + rz * side - lz * back
        // Keep the camera out of walls.
        val ox = px; val oy = eyeY; val oz = pz
        val ddx = cx - ox; val ddy = cy - oy; val ddz = cz - oz
        val dist = sqrt(ddx * ddx + ddy * ddy + ddz * ddz)
        if (dist > 0.05f && map.physics.raycast(ox, oy, oz, ddx / dist, ddy / dist, ddz / dist, dist, hit, Layers.WORLD)) {
            val k = max(0.05f, hit.distance - 0.25f) / dist
            cx = ox + ddx * k; cy = oy + ddy * k; cz = oz + ddz * k
        }
        cy = max(cy, map.heightAt(cx, cz) + 0.3f)
        // Smooth the follow so the world glides instead of snapping.
        if (!camInit) {
            camPosSm.set(cx, cy, cz)
            camTgtSm.set(cx + lx * 10f, cy + ly * 10f, cz + lz * 10f)
            camInit = true
        } else {
            // Softer spring: 15 was stiff enough to transmit footstep jitter
            // and terrain steps straight into the camera. 11 glides.
            val kPos = MathX.damp(0f, 1f, 11f, dt)
            camPosSm.x = MathX.lerp(camPosSm.x, cx, kPos); camPosSm.z = MathX.lerp(camPosSm.z, cz, kPos)
            // Vertical is eased separately and more gently: stairs, ledges and
            // slopes are exactly where a single stiff spring looked like a
            // step-jitter, so height gets its own softer spring.
            val kY = MathX.damp(0f, 1f, 8.5f, dt)
            camPosSm.y = MathX.lerp(camPosSm.y, cy, kY)
            camTgtSm.x = MathX.lerp(camTgtSm.x, cx + lx * 10f, kPos); camTgtSm.y = MathX.lerp(camTgtSm.y, cy + ly * 10f, kY); camTgtSm.z = MathX.lerp(camTgtSm.z, cz + lz * 10f, kPos)
        }
        camPos.set(camPosSm.x, camPosSm.y, camPosSm.z)
        // Explosions near the player kick the view — the world wobbles, then settles.
        if (shake > 0f && shakeEnabled) {
            val s = shake * 0.14f
            camPos.x += (kotlin.random.Random.nextFloat() - 0.5f) * 2f * s
            camPos.y += (kotlin.random.Random.nextFloat() - 0.5f) * 2f * s
        }
        camera.position.set(camPos)
        camera.target.set(camTgtSm.x, camTgtSm.y, camTgtSm.z)
        // Roll is a camera-up tilt, so a slide or a hard landing reads as the
        // body reacting to the ground rather than the world tilting randomly.
        if (lean != 0f) camera.up.set(rx * lean, 1f, rz * lean).nor() else camera.up.set(0f, 1f, 0f)
        // ADS blends the field of view so the zoom glides in instead of popping.
        val wantAds = if (ads) 1f else 0f
        adsBlend = MathX.damp(adsBlend, wantAds, 14f, dt)
        val baseFov = if (ctx.graphics.width in 1 until ctx.graphics.height) 82f else 70f
        camera.fovY = (baseFov / (1f + (zoom - 1f) * adsBlend)) * MathX.DEG_TO_RAD
        camera.near = 0.1f
        camera.far = 420f * ctx.graphics.quality.detailDistance.coerceAtLeast(0.7f)
        @Suppress("UNUSED_VARIABLE") val unused = alpha + dt
    }

    /** Interpolated position the camera follows (our player, or who we spectate). */
    private fun viewTarget(): Triple<Float, Float, Float> {
        val me = local
        val alpha = ctx.time.alpha
        if (me != null && me.alive) {
            val p = prev[localId]
            return if (p != null) Triple(MathX.lerp(p[0], me.pos.x, alpha), MathX.lerp(p[1], me.pos.y, alpha), MathX.lerp(p[2], me.pos.z, alpha))
            else Triple(me.pos.x, me.pos.y, me.pos.z)
        }
        // Spectate: the killer or anyone alive.
        if (isAuthority) {
            val s = sim.players[spectate]?.takeIf { it.alive } ?: sim.players[me?.killedBy ?: -1]?.takeIf { it.alive } ?: sim.players.values.firstOrNull { it.alive }
            if (s != null) { spectate = s.id; return Triple(s.pos.x, s.pos.y, s.pos.z) }
        } else {
            val a = actors[spectate]?.takeIf { it.alive } ?: actors.values.firstOrNull { it.alive && it.id != localId }
            if (a != null) { spectate = a.id; return Triple(a.view[0], a.view[1], a.view[2]) }
        }
        return Triple(me?.pos?.x ?: 0f, me?.pos?.y ?: 0f, me?.pos?.z ?: 0f)
    }

    private fun publishIsland() {
        val me = local ?: return
        if (matchOver) { ctx.island.end(); return }
        val alive = if (isAuthority) sim.aliveCount else actors.values.count { it.alive }
        ctx.island.update(LiveActivity(
            title = "Send Off · $alive alive",
            subtitle = if (me.alive) "${me.health.toInt()} HP · ${me.kills} kills" else "Eliminated · spectating",
            compactText = "$alive alive",
            trailing = "${me.kills} ◎",
            urgent = me.alive && me.health < 30f,
            preferred = IslandStyle.CARD,
        ))
    }

