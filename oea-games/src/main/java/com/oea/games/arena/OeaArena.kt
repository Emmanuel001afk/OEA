    private fun drawWorld(r: Renderer3D) {
        // Hand this frame's dynamic light (fire, sparks, magic) to the scene
        // and register the physics-driven particle systems.
        vfx.register(r, env)
        r.draw(map.terrainMesh, map.terrainMaterial, m.idt())
        // Water breathes with the same wind: a slow vertical swell and a tiny
        // drift, so the sea is not a dead plane next to moving foliage.
        val seaT = ctx.time.elapsed.toFloat()
        val swell = sin(seaT * 0.55f) * 0.06f * map.windStrength
        r.draw(waterMesh, map.water, sin(seaT * 0.17f) * 0.4f * map.windStrength, -0.15f + swell, cos(seaT * 0.13f) * 0.4f * map.windStrength)
        r.draw(map.buildingMesh, map.wallMaterial, m.idt())
        r.draw(map.roofMesh, map.roofMaterial, m.idt())
        r.draw(map.propMesh, map.propMaterial, m.idt())
        // Named points of interest: solid structures by day, glowing beacons
        // by night. Their supply caches are regular loot spots, so they are
        // genuinely interactable rather than scenery.
        r.draw(map.landmarkMesh, map.landmarkMaterial, m.idt())
        if (worldEnv.lanternsOn) r.draw(map.landmarkGlowMesh, map.landmarkGlowMaterial, m.idt())
        val far = camera.far
        // Foliage answers the same wind the bodies feel: canopies sway on a slow
        // per-tree phase, and the gust strength comes from the map's wind.
        val windT = ctx.time.elapsed.toFloat()
        val gust = 0.55f + 0.45f * sin(windT * 0.23f) * sin(windT * 0.077f + 1.3f)
        val swayAmp = map.windStrength * gust
        for ((ti, t) in map.trees.withIndex()) {
            val ddx = t.x - camera.position.x; val ddz = t.z - camera.position.z
            if (ddx * ddx + ddz * ddz > far * far) continue
            r.draw(ArenaMap.treeTrunk, map.trunk, t.x, t.y - 0.2f, t.z, 0f, t.scale)
            // Lean the crown downwind, with a small oscillation so a still tree
            // still breathes. The trunk stays planted.
            val ph = ti * 1.7f
            val lean = swayAmp * (0.06f + 0.03f * sin(windT * 1.6f + ph))
            val ox = map.windX * lean * t.scale * 2.2f
            val oz = map.windZ * lean * t.scale * 2.2f
            r.draw(map.crownMesh, map.leaves, t.x + ox, t.y - 0.2f + kotlin.math.abs(ox) * 0.08f, t.z + oz, 0f, t.scale, t.tint)
        }
        for (rk in map.rocks) r.draw(ArenaMap.rockMesh, map.rock, rk.x, rk.y + rk.sy * 0.2f, rk.z, rk.yaw, 0f, 0f, rk.sx, rk.sy * 1.2f, rk.sz)
        if (worldEnv.lanternsOn) {
            while (landmarkLights.size < map.landmarks.size) landmarkLights.add(PointLight())
            for ((i, lm) in map.landmarks.withIndex()) {
                val dx = lm.x - camera.position.x; val dz = lm.z - camera.position.z
                if (dx * dx + dz * dz > 90f * 90f) continue
                val flicker = 0.9f + 0.1f * sin(ctx.time.elapsed.toFloat() * 3f + i)
                landmarkLights[i].set(lm.x, lm.y + 8f, lm.z, 0xFFFFC887.toInt(), 1.3f * flicker, 22f)
                env.pointLights.add(landmarkLights[i])
            }
        }
        // Loot.
        val t = ctx.time.elapsed.toFloat()
        for (l in sim.loot) {
            if (l.taken) continue
            val ddx = l.x - camera.position.x; val ddz = l.z - camera.position.z
            if (ddx * ddx + ddz * ddz > 70f * 70f) continue
            val mat = lootMaterial(l.kind)
            val bob = sin(t * 2.5f + l.id) * 0.08f
            when (l.kind) {
                LootKind.WEAPON -> { val gw = Weapon.entries[l.value]; r.draw(gunMesh(gw), gunMaterial(gw), l.x, l.y + 0.25f + bob, l.z, t * 1.2f + l.id, 1.3f) }
                LootKind.AMMO -> r.draw(Mesh.unitCube, mat, l.x, l.y + 0.12f + bob, l.z, t + l.id, 0f, 0f, 0.35f, 0.24f, 0.25f)
                LootKind.MEDKIT -> r.draw(Mesh.unitCube, mat, l.x, l.y + 0.15f + bob, l.z, t + l.id, 0f, 0f, 0.4f, 0.28f, 0.28f)
                LootKind.ARMOR -> r.draw(Mesh.unitCube, mat, l.x, l.y + 0.3f + bob, l.z, t + l.id, 0f, 0f, 0.5f, 0.55f, 0.22f)
                LootKind.HELMET -> r.draw(Mesh.unitSphere, mat, l.x, l.y + 0.25f + bob, l.z, t + l.id, 0f, 0f, 0.42f, 0.3f, 0.42f)
                LootKind.GRENADE -> r.draw(Mesh.unitSphere, if (l.value == 0) grenadeMatFrag else grenadeMatSmoke, l.x, l.y + 0.18f + bob, l.z, t + l.id, 0f, 0f, 0.16f, 0.2f, 0.16f)
            }
            r.blobShadow(l.x, l.y - 0.28f, l.z, 0.35f, 0.3f)
        }
        // Players.
        val alpha = ctx.time.alpha
        if (isAuthority) {
            for (p in sim.players.values) {
                if (p.id == localId && p.alive && adsOn && p.weapon.zoom > 2f) continue
                val pr = prev[p.id]
                val x = if (pr != null) MathX.lerp(pr[0], p.pos.x, alpha) else p.pos.x
                val y = if (pr != null) MathX.lerp(pr[1], p.pos.y, alpha) else p.pos.y
                val z = if (pr != null) MathX.lerp(pr[2], p.pos.z, alpha) else p.pos.z
