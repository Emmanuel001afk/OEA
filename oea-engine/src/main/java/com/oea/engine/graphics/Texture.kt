/**
 * A 2D texture created from a [Bitmap] source. The source is kept (or can be
 * regenerated by [factory]) so the texture survives GPU context loss.
 */
class Texture private constructor(
    private val factory: () -> Bitmap,
    val mipmaps: Boolean,
    val repeat: Boolean,
    val nearest: Boolean,
    private val keepSource: Boolean,
) {
    private var id = 0
    private var generation = -1
    private var cached: Bitmap? = null
    var width = 0
        private set
    var height = 0
        private set

    /** Binds to [unit], uploading first if needed. GL thread only. */
    fun bind(unit: Int = 0): Boolean {
        if (generation != Gpu.generation || id == 0) upload()
        GLES30.glActiveTexture(GLES30.GL_TEXTURE0 + unit)
        GLES30.glBindTexture(GLES30.GL_TEXTURE_2D, id)
        return id != 0
    }

    private fun upload() {
        generation = Gpu.generation
        val bmp = cached ?: runCatching(factory).getOrNull() ?: fallbackBitmap()
        width = bmp.width
        height = bmp.height
        id = Gpu.genTexture()
        GLES30.glBindTexture(GLES30.GL_TEXTURE_2D, id)
        val wrap = if (repeat) GLES30.GL_REPEAT else GLES30.GL_CLAMP_TO_EDGE
        GLES30.glTexParameteri(GLES30.GL_TEXTURE_2D, GLES30.GL_TEXTURE_WRAP_S, wrap)
        GLES30.glTexParameteri(GLES30.GL_TEXTURE_2D, GLES30.GL_TEXTURE_WRAP_T, wrap)
        GLES30.glTexParameteri(GLES30.GL_TEXTURE_2D, GLES30.GL_TEXTURE_MAG_FILTER, if (nearest) GLES30.GL_NEAREST else GLES30.GL_LINEAR)
        GLES30.glTexParameteri(GLES30.GL_TEXTURE_2D, GLES30.GL_TEXTURE_MIN_FILTER, when {
            nearest -> GLES30.GL_NEAREST
            mipmaps -> GLES30.GL_LINEAR_MIPMAP_LINEAR
            else -> GLES30.GL_LINEAR
        })
        GLUtils.texImage2D(GLES30.GL_TEXTURE_2D, 0, bmp, 0)
        if (mipmaps && !nearest) {
            GLES30.glGenerateMipmap(GLES30.GL_TEXTURE_2D)
            val aniso = maxAnisotropy
            if (aniso > 1f) GLES30.glTexParameterf(GLES30.GL_TEXTURE_2D, GL_TEXTURE_MAX_ANISOTROPY_EXT, aniso)
        }
        if (keepSource) cached = bmp else if (cached == null && bmp !== cached) bmp.recycle()
    }

    fun dispose() {
        if (generation == Gpu.generation) Gpu.deleteTexture(id)
        id = 0
        generation = -1
    }

    companion object {
        private const val GL_TEXTURE_MAX_ANISOTROPY_EXT = 0x84FE
        internal const val GL_MAX_TEXTURE_MAX_ANISOTROPY_EXT = 0x84FF

        /** Anisotropic filtering level for mipmapped textures (set by the renderer from quality settings). */
        @Volatile internal var maxAnisotropy = 1f

        /** Wraps an existing bitmap; the bitmap must not be recycled while the texture is in use. */
        fun fromBitmap(bitmap: Bitmap, mipmaps: Boolean = true, repeat: Boolean = false, nearest: Boolean = false): Texture =
            Texture({ bitmap }, mipmaps, repeat, nearest, keepSource = true).also { it.cached = bitmap }

        /** Regenerated from [factory] whenever the GPU context is (re)created; saves memory for large procedural textures. */
        fun generated(mipmaps: Boolean = true, repeat: Boolean = false, nearest: Boolean = false, factory: () -> Bitmap): Texture =
            Texture(factory, mipmaps, repeat, nearest, keepSource = false)

        /** Loads from the app's assets folder. */
        fun asset(path: String, mipmaps: Boolean = true, repeat: Boolean = false): Texture = generated(mipmaps, repeat) {
            OeaEngine.context.assets.open(path).use { BitmapFactory.decodeStream(it) }
        }

        /** Builds a texture from ARGB pixels computed by [pixel] (x, y → colour). */
        fun pixels(width: Int, height: Int, mipmaps: Boolean = true, repeat: Boolean = true, nearest: Boolean = false, pixel: (Int, Int) -> Int): Texture =
            generated(mipmaps, repeat, nearest) {
                val px = IntArray(width * height)
                for (y in 0 until height) for (x in 0 until width) px[y * width + x] = pixel(x, y)
                Bitmap.createBitmap(px, width, height, Bitmap.Config.ARGB_8888)
            }

        /** Draws with an Android [Canvas] (gradients, text, shapes). */
        fun canvas(width: Int, height: Int, mipmaps: Boolean = true, repeat: Boolean = false, draw: (Canvas) -> Unit): Texture =
            generated(mipmaps, repeat) {
                val bmp = Bitmap.createBitmap(width, height, Bitmap.Config.ARGB_8888)
                draw(Canvas(bmp))
                bmp
            }

        private fun fallbackBitmap(): Bitmap = Bitmap.createBitmap(intArrayOf(Color.MAGENTA, Color.BLACK, Color.BLACK, Color.MAGENTA), 2, 2, Bitmap.Config.ARGB_8888)

        @Suppress("unused") private val contextType = Context::class.java
    }
}

/** Ready-made procedural textures. Each call creates a new texture. */
object Textures {
    /** 1×1 white, for untextured sprite drawing. */
    val white: Texture by lazy { Texture.pixels(1, 1, mipmaps = false, repeat = false) { _, _ -> Colors.WHITE } }

    fun checker(size: Int = 256, cells: Int = 8, a: Int = 0xFFE0E0E0.toInt(), b: Int = 0xFF9E9E9E.toInt()): Texture =
        Texture.pixels(size, size) { x, y -> if (((x * cells / size) + (y * cells / size)) % 2 == 0) a else b }

    /** Soft round dot (particles, glows, blob shadows): white with smooth alpha falloff. */
    fun softCircle(size: Int = 128, hardness: Float = 0.0f): Texture = Texture.pixels(size, size, repeat = false) { x, y ->
        val dx = (x + 0.5f) / size * 2f - 1f
        val dy = (y + 0.5f) / size * 2f - 1f
        val d = sqrt(dx * dx + dy * dy)
        val a = MathX.clamp01((1f - d) / (1f - hardness).coerceAtLeast(0.01f))
        Colors.argb((a * a * (3f - 2f * a) * 255f).toInt(), 255, 255, 255)
    }

    /** Anti-aliased filled circle (UI). */
    fun circle(size: Int = 256): Texture = Texture.pixels(size, size, repeat = false) { x, y ->
        val r = size / 2f
        val d = sqrt(((x + 0.5f - r) * (x + 0.5f - r) + (y + 0.5f - r) * (y + 0.5f - r)))
        val a = MathX.clamp01(r - d - 0.5f)
        Colors.argb((a * 255f).toInt(), 255, 255, 255)
    }

    /** Anti-aliased ring of relative [thickness] (UI). */
    fun ring(size: Int = 256, thickness: Float = 0.12f): Texture = Texture.pixels(size, size, repeat = false) { x, y ->
        val r = size / 2f
        val d = sqrt(((x + 0.5f - r) * (x + 0.5f - r) + (y + 0.5f - r) * (y + 0.5f - r)))
        val inner = r * (1f - thickness * 2f)
        val a = MathX.clamp01(minOf(r - d - 0.5f, d - inner + 0.5f))
        Colors.argb((a * 255f).toInt(), 255, 255, 255)
    }

    /** Spark streak (bright centre line) for muzzle flashes and speed lines. */
    fun spark(size: Int = 64): Texture = Texture.pixels(size, size, repeat = false) { x, y ->
        val dx = abs((x + 0.5f) / size * 2f - 1f)
        val dy = abs((y + 0.5f) / size * 2f - 1f)
        val a = MathX.clamp01((1f - dx * 2.2f) * (1f - dy))
        Colors.argb((a * a * 255f).toInt(), 255, 255, 255)
    }

    /** Tileable value-noise texture tinted between two colours. */
    fun noise(size: Int = 256, scale: Float = 8f, seed: Long = 7, a: Int = 0xFF707070.toInt(), b: Int = 0xFFB0B0B0.toInt(), octaves: Int = 4): Texture {
        val n = Noise(seed)
        return Texture.pixels(size, size) { x, y ->
            // Tileable by blending four offset samples.
            val u = x / size.toFloat(); val v = y / size.toFloat()
            val s = scale
            val n00 = n.fbm(u * s, v * s, octaves)
            val n10 = n.fbm((u - 1f) * s, v * s, octaves)
            val n01 = n.fbm(u * s, (v - 1f) * s, octaves)
            val n11 = n.fbm((u - 1f) * s, (v - 1f) * s, octaves)
            val value = MathX.lerp(MathX.lerp(n00, n10, u), MathX.lerp(n01, n11, u), v)
            Colors.lerp(a, b, MathX.clamp01(value * 0.5f + 0.5f + 0.0f))
        }
    }

    /** Wood grain (chess boards, crates). */
    fun wood(size: Int = 256, light: Int = 0xFFD9B382.toInt(), dark: Int = 0xFF9A6A3C.toInt(), seed: Long = 3): Texture {
        val n = Noise(seed)
        return Texture.pixels(size, size) { x, y ->
            val u = x / size.toFloat(); val v = y / size.toFloat()
            val warp = n.fbm(u * 3f, v * 12f, 3) * 0.6f
            val rings = sin((u * 18f + warp * 6f) * MathX.PI_F) * 0.5f + 0.5f
            val fine = n.noise(u * 80f, v * 6f) * 0.12f
            Colors.lerp(dark, light, MathX.clamp01(rings * 0.75f + 0.2f + fine))
        }
    }

    /** City facade with lit windows (Runner buildings). */
    fun windows(size: Int = 256, wall: Int = 0xFF2B3140.toInt(), lit: Int = 0xFFFFD27A.toInt(), dark: Int = 0xFF1A1F2A.toInt(), seed: Int = 11): Texture =
        Texture.pixels(size, size) { x, y ->
            val cols = 8; val rows = 8
            val cx = x * cols / size; val cy = y * rows / size
            val fx = (x * cols % size) / size.toFloat(); val fy = (y * rows % size) / size.toFloat()
            val inWindow = fx in 0.18f..0.82f && fy in 0.22f..0.78f
            if (!inWindow) wall else if (Rng.hash01(cx, cy, seed) > 0.45f) lit else dark
        }

    /** Vertical gradient (skies, UI). */
    fun verticalGradient(height: Int = 256, top: Int, bottom: Int): Texture = Texture.canvas(4, height, mipmaps = false) { c ->
        val p = Paint().apply { shader = LinearGradient(0f, 0f, 0f, height.toFloat(), top, bottom, AndroidShader.TileMode.CLAMP) }
        c.drawRect(0f, 0f, 4f, height.toFloat(), p)
    }

    /** Rounded rectangle used for 9-slice UI panels: white, radius = size/2 - 1. */
    fun roundedPanel(size: Int = 64): Texture = Texture.canvas(size, size, mipmaps = false) { c ->
        val p = Paint(Paint.ANTI_ALIAS_FLAG).apply { color = Color.WHITE }
        c.drawRoundRect(RectF(0f, 0f, size.toFloat(), size.toFloat()), size / 2f - 1f, size / 2f - 1f, p)
    }

    /** Radial glow, bright centre fading to transparent. */
    fun glow(size: Int = 128, color: Int = Colors.WHITE): Texture = Texture.canvas(size, size, mipmaps = true) { c ->
        val p = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            shader = RadialGradient(size / 2f, size / 2f, size / 2f, intArrayOf(color, Colors.withAlpha(color, 90), Colors.withAlpha(color, 0)),
                floatArrayOf(0f, 0.35f, 1f), AndroidShader.TileMode.CLAMP)
        }
        c.drawCircle(size / 2f, size / 2f, size / 2f, p)
    }
}
